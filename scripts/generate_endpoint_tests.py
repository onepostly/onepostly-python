#!/usr/bin/env python3
"""Generate endpoint-existence tests from the OpenAPI spec.

For every operation in the spec the generated pytest suite asserts that the
corresponding SDK method exists on the right API class. This catches any
endpoint that regenerates into the client without being surfaced (or gets
dropped from the spec while still claimed by the README).

Run manually or from the generate workflow; output is committed. Stdlib only.
"""

from __future__ import annotations

import argparse
import json
import re
import urllib.request
from pathlib import Path

DEFAULT_SPEC_URL = "https://api.onepostly.com/openapi.json"
HTTP_METHODS = {"get", "post", "put", "patch", "delete"}


def load_spec(path: str | None) -> dict:
    if path:
        return json.loads(Path(path).read_text(encoding="utf-8"))
    # The API gateway rejects requests without a User-Agent (403).
    request = urllib.request.Request(
        DEFAULT_SPEC_URL, headers={"User-Agent": "onepostly-sdk-scripts"}
    )
    with urllib.request.urlopen(request) as response:
        return json.loads(response.read().decode("utf-8"))


def collect_classes(spec: dict) -> dict[str, list[str]]:
    classes: dict[str, list[str]] = {}
    for methods in (spec.get("paths") or {}).values():
        for verb, op in methods.items():
            if verb not in HTTP_METHODS:
                continue
            tags = op.get("tags") or []
            operation_id = op.get("operationId")
            if not tags or not operation_id:
                continue
            # openapi-generator's snake_case conversion (mirrors the reference
            # script) so asserted names match the generated methods exactly.
            step = re.sub(r"([A-Z]+)([A-Z][a-z])", r"\1_\2", operation_id)
            step = re.sub(r"([a-z\d])([A-Z])", r"\1_\2", step)
            method_name = step.replace("-", "_").lower()
            classes.setdefault(f"{tags[0]}Api", []).append(method_name)
    for methods in classes.values():
        methods.sort()
    return classes


def generate_test_file(spec: dict) -> str:
    classes = collect_classes(spec)
    lines = [
        '"""Auto-generated endpoint tests from the OpenAPI spec.',
        "",
        "DO NOT EDIT THIS FILE MANUALLY.",
        "Run `python scripts/generate_endpoint_tests.py` to regenerate.",
        '"""',
        "",
        "import pytest",
        "",
    ]
    for class_name in classes:
        lines.append(f"from onepostly.api.{snake(class_name[:-3])}_api import {class_name}")
    lines += [
        "",
        "",
        "@pytest.mark.parametrize(",
        '    "api_class, method_name",',
        "    [",
    ]
    for class_name, methods in classes.items():
        for method_name in methods:
            lines.append(f'        ({class_name}, "{method_name}"),')
    lines += [
        "    ],",
        ")",
        "def test_spec_endpoints_surface_as_sdk_methods(api_class, method_name):",
        '    """Every spec operation must exist as a method on its API class."""',
        "    assert callable(getattr(api_class, method_name, None))",
        "",
    ]
    return "\n".join(lines)


def snake(name: str) -> str:
    step = re.sub(r"([A-Z]+)([A-Z][a-z])", r"\1_\2", name)
    step = re.sub(r"([a-z\d])([A-Z])", r"\1_\2", step)
    return step.replace("-", "_").lower()


def main() -> None:
    parser = argparse.ArgumentParser(description="Generate endpoint-existence tests.")
    parser.add_argument("--spec", help="Path to a local OpenAPI spec (default: fetch live spec)")
    parser.add_argument("--out", default="tests/test_endpoints.py")
    args = parser.parse_args()
    Path(args.out).write_text(generate_test_file(load_spec(args.spec)), encoding="utf-8")
    print(f"Endpoint tests generated in {args.out}.")


if __name__ == "__main__":
    main()
